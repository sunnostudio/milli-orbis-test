def _build_cape(en, jp, png_dir, hotspot, out_path):
    """Build minimal Mousecape .cape plist with 15 cursors"""
    try:
        from PIL import Image
    except Exception as e:
        print(f" cape skip {en}: Pillow missing {e}")
        return False
    cursors = {}
    for png_name, hs in hotspot.items():
        base = png_name.replace(".png", "")
        apple_id = CAPE_MAP.get(base)
        if not apple_id:
            continue
        png_path = png_dir / png_name
        if not png_path.exists():
            continue
        # skip duplicate Apple ids (keep first)
        if apple_id in cursors:
            continue
        try:
            im = Image.open(png_path)
            w, h = im.size
        except Exception:
            w, h = 32, 32
        # load png bytes as Data
        data = png_path.read_bytes()
        # PointsWide/High = image size at 1x
        # HotSpot from hotspot.json
        hx, hy = hs if isinstance(hs, (list, tuple)) and len(hs)==2 else (0,0)
        cursors[apple_id] = {
            "FrameCount": 1,
            "FrameDuration": 1.0,
            "HotSpotX": float(hx),
            "HotSpotY": float(hy),
            "PointsWide": float(w),
            "PointsHigh": float(h),
            "Representations": [data],
        }
    # fallback: ensure at least Arrow exists, else add arrow.png
    if "com.apple.coregraphics.Arrow" not in cursors:
        ap = png_dir / "arrow.png"
        if ap.exists():
            hs = hotspot.get("arrow.png", [4,4])
            data = ap.read_bytes()
            cursors["com.apple.coregraphics.Arrow"] = {
                "FrameCount": 1, "FrameDuration": 1.0,
                "HotSpotX": float(hs[0]), "HotSpotY": float(hs[1]),
                "PointsWide": 32.0, "PointsHigh": 32.0,
                "Representations": [data],
            }
    cape = {
        "Author": "Milli Orbis",
        "CapeName": f"MilliOrbis-{en}",
        "CapeVersion": 1.0,
        "Identifier": f"com.milli-orbis.{en.lower()}",
        "Version": 2.0,
        "MinimumVersion": 2.0,
        "Cloud": False,
        "HiDPI": True,
        "Cursors": cursors,
    }
    out_path.parent.mkdir(parents=True, exist_ok=True)
    with open(out_path, "wb") as f:
        plistlib.dump(cape, f, fmt=plistlib.FMT_XML)
    return True

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--win", action="store_true", help="Generate Windows zips")
    parser.add_argument("--mac", action="store_true", help="Generate Mac zips")
    parser.add_argument("--chromebook", action="store_true", help="Generate Chromebook zips")
    parser.add_argument("--all", action="store_true", help="Generate all")
    args = parser.parse_args()
    do_win = args.win or args.all or (not args.win and not args.mac and not args.chromebook)
    do_mac = args.mac or args.all
    do_cb = args.chromebook or args.all

    CURSORS_ROOT.mkdir(parents=True, exist_ok=True)
    DIST_ROOT.mkdir(parents=True, exist_ok=True)
    # Clean dist subfolders based on flags
    if args.all and DIST_ROOT.exists():
        shutil.rmtree(DIST_ROOT)
        DIST_ROOT.mkdir(parents=True, exist_ok=True)
    (DIST_ROOT / "win").mkdir(parents=True, exist_ok=True)
    (DIST_ROOT / "mac").mkdir(parents=True, exist_ok=True)
    (DIST_ROOT / "chromebook").mkdir(parents=True, exist_ok=True)
    # Keep legacy flat for backward compat (win)
    # Clean legacy flat zips if regenerating win
    if do_win:
        for p in DIST_ROOT.glob("*.zip"):
            p.unlink()

    for tid, en, jp in TALENTS:
        cur_folder_name = CUR_FOLDER[tid]
        scheme = f"MilliOrbis-{en}"
        cur_dir = CURSORS_ROOT / cur_folder_name
        if not cur_dir.exists():
            print(f"skip {tid}: no folder {cur_dir}")
            continue
        # Verify 15 files exist
        missing = [f for f in FIFTEEN if not (cur_dir / f).exists()]
        if missing:
            print(f"warn {tid} missing {missing}")

        # Generate install.inf, README.md, LICENSE, install.bat, preview.png inside cur_dir (for verification)
        inf_content = INF_TEMPLATE.format(SCHEME=scheme, JP=jp, EN=en)
        readme_content = README_TEMPLATE.format(JP=jp, EN=en)
        bat_content = BAT_TEMPLATE.format(EN=en)

        # Write to cursor folder (for direct browsing) and also to dist staging
        (cur_dir / "install.inf").write_text(inf_content, encoding="utf-8")
        (cur_dir / "README.md").write_text(readme_content, encoding="utf-8")
        (cur_dir / "LICENSE").write_text(LICENSE_TEXT, encoding="utf-8")
        (cur_dir / "install.bat").write_text(bat_content, encoding="utf-8")
        # preview.png: copy from root png (arrow-derived)
        src_png = CURSORS_ROOT / f"{cur_folder_name}.png"
        dst_preview = cur_dir / "preview.png"
        if src_png.exists():
            shutil.copy(src_png, dst_preview)
        else:
            # fallback
            print(f"no preview source for {tid}")

        # Now create zips per OS
        # -- Win
        if do_win:
            zip_name = f"MilliOrbis-{en}.zip"
            for out_dir in [DIST_ROOT, DIST_ROOT / "win"]:
                out_dir.mkdir(parents=True, exist_ok=True)
                zip_path = out_dir / zip_name
                with zipfile.ZipFile(zip_path, "w", zipfile.ZIP_DEFLATED) as zf:
                    base = f"MilliOrbis-{en}/"
                    for fname in FIFTEEN:
                        src = cur_dir / fname
                        if src.exists():
                            zf.write(src, base + fname)
                    zf.write(cur_dir / "install.inf", base + "install.inf")
                    zf.write(cur_dir / "README.md", base + "README.md")
                    zf.write(cur_dir / "LICENSE", base + "LICENSE")
                    zf.write(cur_dir / "install.bat", base + "install.bat")
                    if dst_preview.exists():
                        zf.write(dst_preview, base + "preview.png")
                print(f"generated win {zip_path} ({zip_path.stat().st_size} bytes)")
        # -- Mac / Chromebook: png + hotspot.json
        # Generate png dir + hotspot.json once per talent
        # Ensure png extraction (Pillow) – use existing root png as preview but also extract 15 pngs
        if do_mac or do_cb:
            from PIL import Image
            png_dir = cur_dir / "png"
            png_dir.mkdir(exist_ok=True)
            hotspot = {}
            for fname in FIFTEEN:
                cur_path = cur_dir / fname
                png_name = fname.replace(".cur", ".png")
                dst_png = png_dir / png_name
                try:
                    im = load_cur_rgba(cur_path)
                    im.save(dst_png, "PNG")
                    hotspot[png_name] = _extract_hotspots(cur_path)
                except Exception as e:
                    # fallback copy existing root png for arrow
                    if png_name == "arrow.png" and (CURSORS_ROOT / f"{cur_folder_name}.png").exists():
                        shutil.copy(CURSORS_ROOT / f"{cur_folder_name}.png", dst_png)
                        hotspot[png_name] = [1,1]
                    else:
                        print(f" png extract failed {tid}/{fname}: {e}")
